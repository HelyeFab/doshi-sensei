interface KanjiDetails {
  kanji: string;
  grade?: number | null;
  jlpt?: number | null;
  stroke_count?: number;
  meanings?: string[];
  kun_readings?: string[];
  on_readings?: string[];
  heisig_en?: string | null;
  frequency?: number | null;
  components?: string[];
}

async function fetchKanjiDetails(kanji: string): Promise<KanjiDetails | null> {
  const url = `${KANJI_API}/kanji/${encodeURIComponent(kanji)}`;
  const data = await fetchWithCache(url);
  
  if (!data) return null;
  
  return {
    kanji: data.kanji,
    grade: data.grade ?? null,
    jlpt: data.jlpt ?? null,
    stroke_count: data.stroke_count,
    meanings: data.meanings || [],
    kun_readings: data.kun_readings || [],
    on_readings: data.on_readings || [],
    heisig_en: data.heisig_en ?? null,
    frequency: data.freq ?? null,
    components: extractComponents(data)
  };
}

function extractComponents(kanjiData: any): string[] {
  const components: string[] = [];
  
  // Add radical if present
  if (kanjiData.radical) {
    components.push(kanjiData.radical);
  }
  
  // Add parts if present
  if (kanjiData.parts && Array.isArray(kanjiData.parts)) {
    components.push(...kanjiData.parts);
  }
  
  return [...new Set(components)]; // Remove duplicates
}

