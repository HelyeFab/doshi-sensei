function sortKanjiByDifficulty(kanji: KanjiDetails[]): KanjiDetails[] {
  return kanji.sort((a, b) => {
    // First sort by JLPT (N5 = easiest)
    const jlptOrder: Record<number, number> = { 5: 1, 4: 2, 3: 3, 2: 4, 1: 5 };
    const jlptA = a.jlpt ? jlptOrder[a.jlpt] || 99 : 99;
    const jlptB = b.jlpt ? jlptOrder[b.jlpt] || 99 : 99;
    if (jlptA !== jlptB) return jlptA - jlptB;
    
    // Then by grade
    const gradeA = a.grade ?? 99;
    const gradeB = b.grade ?? 99;
    if (gradeA !== gradeB) return gradeA - gradeB;
    
    // Then by frequency (lower = more common)
    const freqA = a.frequency ?? 9999;
    const freqB = b.frequency ?? 9999;
    if (freqA !== freqB) return freqA - freqB;
    
    // Finally by stroke count
    const strokeA = a.stroke_count ?? 999;
    const strokeB = b.stroke_count ?? 999;
    return strokeA - strokeB;
  });
}

